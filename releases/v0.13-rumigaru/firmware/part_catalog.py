def _mix(a, b):
    return tuple((a[i] + b[i]) // 2 for i in range(3))


def _expanded(colors):
    transparent, outline, shadow, main, highlight, accent, neutral, eye = colors
    # One colour family per creature: remove the competing neutral/accent ramps.
    soft_light = _mix(main, neutral)
    return (transparent, outline,
            shadow, main, soft_light,
            shadow, main, main,
            shadow, soft_light, soft_light,
            eye)


